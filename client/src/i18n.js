function lookup(lang, key) {
  return key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), messages[lang]);
}

/** Dịch `key` theo ngôn ngữ hiện tại. Thiếu bản tiếng Anh thì rơi về tiếng Việt, thiếu nữa thì trả lại key. */
export function t(key, params = {}) {
  let v = lookup(locale.value, key);
  if (v === undefined) v = lookup('vi', key);
  if (v === undefined) return key;
  if (typeof v === 'function') return v(params);
  if (typeof v !== 'string') return v; // mảng (thứ, tháng, tâm trạng)
  return v.replace(/\{(\w+)\}/g, (m, name) => (params[name] ?? m));
}
